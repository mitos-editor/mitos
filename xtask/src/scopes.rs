//! Scope inventory generation and spelling checks, independent of native grammars.

use crate::DynError;
use std::{collections::BTreeSet, fs, path::Path};

/// Scan query tokens, skipping strings and comments so predicate text cannot
/// accidentally declare public captures. Private helpers must start with `_`.
fn captures(source: &str) -> BTreeSet<String> {
    let mut result = BTreeSet::new();
    let mut bytes = source.bytes().peekable();
    while let Some(byte) = bytes.next() {
        match byte {
            b';' => {
                for byte in bytes.by_ref() {
                    if byte == b'\n' {
                        break;
                    }
                }
            }
            b'"' => {
                while let Some(byte) = bytes.next() {
                    if byte == b'\\' {
                        bytes.next();
                    } else if byte == b'"' {
                        break;
                    }
                }
            }
            b'@' => {
                let mut name = String::new();
                while let Some(&byte) = bytes.peek() {
                    if !byte.is_ascii_alphanumeric() && !matches!(byte, b'.' | b'_' | b'-') {
                        break;
                    }
                    name.push(byte as char);
                    bytes.next();
                }
                if let Some(class) = name.strip_prefix("local.definition.") {
                    result.insert(class.to_owned());
                } else if !name.is_empty()
                    && !name.starts_with('_')
                    && name != "none"
                    && name != "local"
                    && !name.starts_with("local.")
                {
                    result.insert(name);
                }
            }
            _ => {}
        }
    }
    result
}

pub fn inventory() -> Result<BTreeSet<String>, DynError> {
    let mut all = BTreeSet::new();
    for entry in fs::read_dir(crate::path::ts_queries())? {
        let path = entry?.path();
        if !path.is_dir() {
            continue;
        }
        for file in ["highlights.scm", "locals.scm"] {
            let file = path.join(file);
            if !file.is_file() {
                continue;
            }
            for capture in captures(&fs::read_to_string(&file)?) {
                if !theme::scopes::is_syntax_selector(&capture) {
                    return Err(format!("{}: unknown highlight capture @{capture}; use a documented scope or prefix a helper with '_'", file.display()).into());
                }
                all.insert(capture);
            }
        }
    }
    Ok(all)
}

fn generated(captures: &BTreeSet<String>) -> String {
    let mut result = String::from(
        "// Generated by cargo xtask docgen. Do not edit.\npub const CAPTURES: &[&str] = &[\n",
    );
    for capture in captures {
        result.push_str(&format!("    {capture:?},\n"));
    }
    result.push_str("];\n");
    result
}

pub fn generate() -> Result<String, DynError> {
    let inventory = inventory()?;
    fs::write(
        crate::path::project_root().join("crates/theme/src/scopes/captures.rs"),
        generated(&inventory),
    )?;
    let mut doc = String::from("<!-- Generated by cargo xtask docgen. Do not edit. -->\n\n");
    for (title, entries) in [
        ("Syntax kinds", theme::scopes::KINDS),
        ("Occurrence roles and traits", theme::scopes::QUALIFIERS),
        ("Interface scopes", theme::scopes::INTERFACE),
    ] {
        doc.push_str(&format!(
            "#### {title}\n\n| Name | Meaning |\n| --- | --- |\n"
        ));
        for (name, meaning) in entries {
            doc.push_str(&format!("| `{name}` | {} |\n", meaning.replace('|', "\\|")));
        }
        doc.push('\n');
    }
    Ok(doc.trim_end().to_owned() + "\n")
}

pub fn check() -> Result<(), DynError> {
    let expected = generated(&inventory()?);
    let path = crate::path::project_root().join("crates/theme/src/scopes/captures.rs");
    if fs::read_to_string(path)? != expected {
        return Err("Highlight inventory is stale; run cargo xtask docgen".into());
    }
    for file in fs::read_dir(crate::path::runtime().join("themes"))? {
        let file = file?.path();
        if file.extension().is_none_or(|ext| ext != "toml") {
            continue;
        }
        check_theme(&file)?;
    }
    check_theme(&crate::path::project_root().join("base16_theme.toml"))?;
    println!("Scope check succeeded");
    Ok(())
}

fn check_theme(file: &Path) -> Result<(), DynError> {
    let value: toml::Table = toml::from_str(&fs::read_to_string(file)?)
        .map_err(|error| format!("{}: {}", file.display(), error.message()))?;
    for key in value.keys() {
        if !matches!(key.as_str(), "palette" | "inherits" | "rainbow")
            && !theme::scopes::is_known(key)
        {
            return Err(format!("{}: unknown theme scope {key:?}", file.display()).into());
        }
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;
    #[test]
    fn scanner_ignores_predicate_strings_comments_and_structural_captures() {
        let found = captures(
            r#"
            ; @typo
            (identifier) @variable.parameter @_helper @none
            (#match? @_helper "@not_a_scope\\\"still_a_string")
            (identifier) @local.definition.variable.mutable
            (block) @local.scope
        "#,
        );
        assert_eq!(
            found,
            BTreeSet::from(["variable.parameter".into(), "variable.mutable".into()])
        );
    }
}
